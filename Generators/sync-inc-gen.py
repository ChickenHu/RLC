#! python3
# coding=utf-8

from pathlib import Path

# TH06 PDF, page 3: timer clock 160 MHz, PSC = 0.
TIMER_CLOCK_HZ = 160_000_000
TARGET_CAPTURE_SAMPLES = 2048
MODES = [
    ("Mode1", 2, 256, 256),
    ("Mode2", 3, 160, 160),
    ("Mode3", 4, 80, 80),
    ("Mode4", 5, 32, 16),
]

H_TEMPLATE = "extern const Mode_t {name};\n"
C_TEMPLATE = """
const Mode_t {name} = {{
    .dds_table = SINE_WAVE_{dac_points}.value,
    .dds_points = {dac_points},
    .adc_points = {adc_points},
    .capture_cycles = {capture_cycles},
    .dac_arr = {dac_arr},
    .adc_arr = {adc_arr},
    .dds_freq = FREQ_1E{exponent},
}};
"""


def timer_arr(name, rate):
    period, remainder = divmod(TIMER_CLOCK_HZ, rate)
    if remainder or not 1 <= period <= 65536:
        raise ValueError(f"{name}: frequency requires an invalid timer period")
    return period - 1


def main():
    header = ["/* Generated by Generators/sync-inc-gen.py. */\n\n"]
    source = ["/* Generated by Generators/sync-inc-gen.py. */\n"]
    for name, exponent, dac_points, adc_points in MODES:
        frequency = 10 ** exponent
        header.append(H_TEMPLATE.format(name=name))
        capture_cycles = (TARGET_CAPTURE_SAMPLES + adc_points - 1) // adc_points
        source.append(C_TEMPLATE.format(name=name, dac_points=dac_points, adc_points=adc_points,
                                        capture_cycles=capture_cycles,
                                        dac_arr=timer_arr(name, frequency * dac_points),
                                        adc_arr=timer_arr(name, frequency * adc_points),
                                        exponent=exponent))

    assets = Path(__file__).resolve().parents[1] / "Core/Inc/Assets"
    assets.mkdir(parents=True, exist_ok=True)
    (assets / "sync.h.inc").write_text("".join(header), encoding="utf-8")
    (assets / "sync.c.inc").write_text("".join(source), encoding="utf-8")


if __name__ == "__main__":
    main()
